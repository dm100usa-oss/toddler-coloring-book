import React from "react";

/* Слова с черточкой внутри не должны разрываться на переносе.

   Браузер считает любую черточку внутри слова местом, где строку
   можно разрезать. Из-за этого в тексте появлялось "E-Mail-" в конце
   одной строки и "Adresse." в начале следующей. Читается это как
   опечатка, особенно когда края текста выровнены по ширине и глазу
   не за что зацепиться.

   Неразрывной черточки в шрифтах сайта нет, проверено: вместо нее
   вылез бы пустой квадратик. Поэтому слово оборачивается в кусок,
   которому запрещено переноситься.

   Длинные составные слова оставляем как есть: если слово длиннее
   двадцати четырех знаков, запрет переноса сам создаст дыру
   в строке, и лекарство окажется хуже болезни.

   Затрагивает только настоящие слова: E-Mail-Adresse, non-toxic,
   peut-etre, A4-Format, номера ISBN. Обычные тексты без черточек
   проходят насквозь и не меняются вовсе. */

const TOKEN = /(\S*[^\s-]-[^\s-]\S*)/g;

const MAX = 24;

export function nb(text: string): React.ReactNode {
  if (!text.includes("-")) return text;

  const parts = text.split(TOKEN);
  const out: React.ReactNode[] = [];

  parts.forEach((part, i) => {
    if (!part) return;
    /* Нечетные куски это сами слова с черточкой, четные текст между
       ними. Так работает разрезание строки по образцу со скобками. */
    const isWord = i % 2 === 1;
    if (isWord && part.length <= MAX) {
      out.push(
        <span className="nb" key={i}>
          {part}
        </span>
      );
    } else {
      out.push(part);
    }
  });

  return out;
}
