
/* ---------------------------------------------------------------------------
   Продажа файлов для печати прямо на этом сайте.

   Деньги принимает Stripe, файл выдается по ссылке, которая подписана
   и живет ограниченное время.

   Здесь только то, что можно показывать в браузере: цена, размеры
   листа и список книг. Работа с тайным словом и адреса файлов лежат
   отдельно, в pdfAssets.ts, и на страницу не попадают.

   Сами рукописи лежат в папке knigi и в открытый доступ не попадают.
   Перед сборкой сайта скрипт scripts/prepare-pdfs.mjs раскладывает их
   в public/dl под именами, которые невозможно угадать: имя папки
   считается из тайного слова DOWNLOAD_SECRET. Прямой ссылки на них
   нигде нет, в карту сайта они не попадают, роботам закрыты.

   Устройство временное и это осознанно. Позже книги переедут в файловое
   хранилище Vercel. Чтобы переезд был правкой в одном месте, все знание
   о том, где лежит файл, собрано в функции assetPath в pdfAssets.ts.
   Больше нигде на сайте папка knigi и папка public/dl не упоминаются.
--------------------------------------------------------------------------- */

