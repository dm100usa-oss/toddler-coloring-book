
/* ---------------------------------------------------------------------------
   Продажа файлов для печати прямо на этом сайте.

   Деньги принимает Stripe, файл выдается по ссылке, которая подписана
   и живет ограниченное время.

   Здесь только то, что можно показывать в браузере: цена, размеры
   листа и список книг. Работа с тайным словом и адреса файлов лежат
   отдельно, в pdfAssets.ts, и на страницу не попадают.

   Сами рукописи лежат в закрытом файловом хранилище Vercel Blob,
   в папке этого сайта. Публичного адреса у них нет вовсе: забрать файл
   может только сам сайт, и только после проверки оплаты. Убедившись,
   что покупка настоящая, он выписывает на файл разовый пропуск
   на пятнадцать минут и отправляет покупателя по нему.

   Все знание о том, где лежит файл, собрано в функции blobPath
   в pdfAssets.ts. Больше нигде на сайте место хранения не упоминается.
--------------------------------------------------------------------------- */

