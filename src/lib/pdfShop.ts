/** Книги, у которых есть готовый файл на продажу. Три издания одной
    книги: английское, испанское и русское. Имена те же, что в каталоге
    издательства, потому что рукопись одна и та же.

    Список повторяет то, что стоит у изданий в book.ts. Проверка ниже
    следит, чтобы эти два места не разошлись. */
export const pdfBookIds = [
  "first-coloring-book-111-en",
  "first-coloring-book-111-es",
  "first-coloring-book-111-ru",
] as const;

export type PdfBookId = (typeof pdfBookIds)[number];

export function hasPdf(id: string | undefined): id is PdfBookId {
  return !!id && (pdfBookIds as readonly string[]).includes(id);
}

