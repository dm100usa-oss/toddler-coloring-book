import { drawings } from "./drawings";
import { wordsDe } from "./wordsDe";
import { wordsFr, wordsNl, wordsPl, wordsIt } from "./wordsEuro";
import type { EuroLang, EditionLang } from "./euro";

/* ---------------------------------------------------------------------------
   Список всех 111 слов книги на двух языках сразу.

   Зачем. Страновая страница обещает первые английские или испанские слова,
   а самих слов на ней не было ни одного. Родитель видел обещание, но не мог
   проверить, какие именно слова получит ребенок.

   Теперь он видит все 111 пар: слово на своем языке и слово из книги.
   Это не только честнее. Это единственное место в интернете, где такой
   список есть, и по нему страница отвечает на запросы вроде "Löwe auf
   Englisch" или "Tiere auf Englisch für Kinder", которых сейчас никто
   не закрывает.

   И еще одно, попутное. Две страницы одной страны, про английскую книгу
   и про испанскую, различались раньше одним словом в заголовке. Теперь
   у одной 111 английских слов, у другой 111 испанских, и это две разные
   страницы по сути.

   Испания и Канада обеспечены без словаря: у Испании язык страницы
   испанский, у Канады английский, и оба уже есть в data/drawings.ts.

   Словари есть у всех пяти стран, где нужен свой язык: немецкий,
   французский, голландский, польский, итальянский. Все двенадцать
   страниц список показывают.
--------------------------------------------------------------------------- */

/** Слово на языке страны. Пусто значит словаря для этой страны еще нет. */
const localWords: Partial<Record<EuroLang, Record<number, string>>> = {
  de: wordsDe,
  fr: wordsFr,
  nl: wordsNl,
  pl: wordsPl,
  it: wordsIt,
};

/** Есть ли у этой страны список слов на ее языке. */
export const hasWordList = (lang: EuroLang) =>
  lang === "espana" || lang === "canada" || lang in localWords;

/**
 * Пары слов для одной страницы: слово на языке страницы и слово из книги.
 * Возвращает пустой список, если словаря для страны еще нет.
 */
export function wordPairs(
  lang: EuroLang,
  ed: EditionLang
): { n: number; group: string; local: string; book: string }[] {
  if (!hasWordList(lang)) return [];

  return drawings.map((d) => {
    /* У Испании язык страницы испанский, у Канады английский: слово
       берется прямо из данных книги, отдельного словаря не нужно. */
    const local =
      lang === "espana"
        ? d.name.es
        : lang === "canada"
          ? d.name.en
          : (localWords[lang]![d.n] ?? d.name.en);

    return { n: d.n, group: d.group, local, book: d.name[ed] };
  });
}
