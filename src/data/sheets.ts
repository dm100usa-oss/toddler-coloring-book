/* Страницы для печати.

   Их ровно десять, и это не случайное число. Десять хватает, чтобы
   родитель понял, подходит ли такая книга его ребенку, и не хватает,
   чтобы заменить книгу. Сайт коммерческий, и раздавать половину
   каталога даром здесь незачем.

   Все десять взяты из самой книги, которую сайт продает, и идут
   в том же порядке, что и в ней. Это важно: страница для печати
   тут не приманка со стороны, а честный образец. Родитель печатает
   лист, видит толщину контура и размер рисунка своими глазами,
   и дальше решает сам.

   Файлы лежат в /printables. Английский лист: <id>. Испанский: <id>-es.
   Русский: <id>-ru.
   У каждого три файла: превью .webp и две версии для печати,
   -letter.pdf для американской бумаги и -a4.pdf для остального мира. */

export type Sheet = {
  id: string;
  name: Record<UiLang, string>;
  /** Насколько лист сложен для ребенка: 1 самый простой, 3 самый
      подробный. Уровень не назначен на глаз, он посчитан по двум
      признакам, которые видно на самом листе.

      Первый: сколько внутри рисунка отдельных участков, которые можно
      закрасить разным цветом. Считается по файлу листа.
      Второй: толщина контура, измеренная на листе формата US Letter.

      Получилось так: носорог 11 участков и контур 4,3 мм, лев 12 и
      3,8, кенгуру 14 и 4,5, медведь 15 и 4,8. Это первый уровень.
      Слон 14 и 2,7, лиса 16 и 3,8, обезьяна 17 и 3,6 это второй.
      Жираф 21 и 2,4, зебра 21 и 3,4, крокодил 22 и 3,4 это третий.

      Числа настоящие и проверяемые: любой может распечатать лист
      и приложить линейку. */
  level: 1 | 2 | 3;
};

